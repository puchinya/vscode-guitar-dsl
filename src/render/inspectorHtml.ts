import { getMessages, type SupportedLocale } from '../i18n';
import type { InspectorContext } from '../inspector/inspectorController';

export function renderInspectorHtml(
  locale: SupportedLocale,
  context: InspectorContext,
  cspSource: string,
  nonce: string,
  generation = 0
): string {
  const messages = getMessages(locale);
  const status = context.kind === 'document' ? messages.inspectorDocumentStatus
    : context.kind === 'progression' ? messages.uiProgressionTitle : messages.inspectorEmptyStatus;
  const description = context.kind === 'document' ? messages.inspectorDocumentDescription
    : context.kind === 'progression' ? messages.uiProgressionDescription : messages.inspectorEmptyDescription;
  const safeNonce = escapeHtml(nonce);
  const safeGeneration = Number.isSafeInteger(generation) && generation >= 0 ? generation : 0;
  const labels = {
    heading: messages.inspectorHeading,
    progressionTitle: messages.uiProgressionTitle,
    bars: messages.uiProgressionBars,
    lengthFour: messages.progressionLengthFour,
    lengthEight: messages.progressionLengthEight,
    lengthSixteen: messages.progressionLengthSixteen,
    operation: messages.progressionOperationPrompt,
    replace: messages.progressionReplace,
    append: messages.progressionAppend,
    candidates: messages.progressionCandidatePrompt,
    play: messages.uiProgressionAudition,
    auditionMode: messages.uiProgressionAuditionMode,
    repeatNotice: messages.uiProgressionRepeatNotice,
    stop: messages.uiStop,
    sideA: messages.uiProgressionSideA,
    sideB: messages.uiProgressionSideB,
    speed: messages.uiProgressionSpeed,
    apply: messages.uiProgressionApply,
    cancel: messages.uiProgressionClose,
    emptyStatus: messages.inspectorEmptyStatus,
    emptyDescription: messages.inspectorEmptyDescription,
    documentStatus: messages.inspectorDocumentStatus,
    documentDescription: messages.inspectorDocumentDescription,
    loading: locale === 'ja' ? '候補を計算しています…' : 'Calculating candidates…'
  };
  const webviewContext = context.kind === 'document' ? { kind: 'document' } : context;
  const repeatNoticeVisibility = context.kind === 'progression' && context.target.bars > 4 ? '' : ' hidden';
  const initial = { context: webviewContext, status, description };
  const safeLabels = escapeJsonForHtml(JSON.stringify(labels));
  const safeInitial = escapeJsonForHtml(JSON.stringify(initial));
  const csp = [
    "default-src 'none'",
    'img-src ' + escapeHtml(cspSource),
    "font-src 'none'",
    "style-src 'nonce-" + safeNonce + "'",
    "script-src 'nonce-" + safeNonce + "'",
    "connect-src 'none'",
    "base-uri 'none'",
    "form-action 'none'"
  ].join('; ');

  return [
    '<!DOCTYPE html>',
    '<html lang="' + locale + '">',
    '<head>',
    '  <meta charset="UTF-8">',
    '  <meta name="viewport" content="width=device-width, initial-scale=1.0">',
    '  <meta http-equiv="Content-Security-Policy" content="' + csp + '">',
    '  <title>' + escapeHtml(messages.inspectorHeading) + '</title>',
    '  <style nonce="' + safeNonce + '">',
    '    :root { color-scheme: light dark; }',
    '    * { box-sizing: border-box; }',
    '    html, body { min-height: 100%; }',
    '    body { margin: 0; background: var(--vscode-sideBar-background); color: var(--vscode-foreground); font-family: var(--vscode-font-family); font-size: var(--vscode-font-size); line-height: 1.45; }',
    '    main { width: min(100%, 46rem); margin: 0 auto; padding: clamp(12px, 4vw, 22px); }',
    '    h1 { margin: 0 0 12px; font-size: 1.15em; font-weight: 600; }',
    '    h2 { margin: 0 0 8px; font-size: 1em; font-weight: 600; }',
    '    .status { margin: 0 0 8px; padding-left: 10px; border-left: 2px solid var(--vscode-focusBorder); font-weight: 600; }',
    '    .description { margin: 0; color: var(--vscode-descriptionForeground); overflow-wrap: anywhere; }',
    '    [hidden] { display: none !important; }',
    '    section { margin-top: 18px; }',
    '    fieldset { min-width: 0; margin: 0 0 14px; padding: 0; border: 0; }',
    '    legend { margin-bottom: 6px; color: var(--vscode-descriptionForeground); font-weight: 600; }',
    '    .choice-row, .toolbar { display: flex; flex-wrap: wrap; gap: 6px; }',
    '    button, select { min-height: 30px; padding: 4px 9px; border: 1px solid var(--vscode-button-border, transparent); border-radius: 2px; background: var(--vscode-button-secondaryBackground); color: var(--vscode-button-secondaryForeground); font: inherit; }',
    '    button { cursor: pointer; }',
    '    button:hover:not(:disabled) { background: var(--vscode-button-secondaryHoverBackground); }',
    '    button[aria-pressed="true"] { outline: 1px solid var(--vscode-focusBorder); outline-offset: -2px; }',
    '    button:focus-visible, select:focus-visible { outline: 2px solid var(--vscode-focusBorder); outline-offset: 1px; }',
    '    button:disabled, select:disabled { cursor: default; opacity: .55; }',
    '    .candidate-list { display: grid; gap: 7px; margin: 0; padding: 0; list-style: none; }',
    '    .candidate-list button { display: grid; width: 100%; gap: 4px; min-height: 52px; padding: 9px 10px; text-align: left; background: var(--vscode-list-inactiveSelectionBackground, var(--vscode-editor-background)); color: var(--vscode-foreground); }',
    '    .candidate-list button[aria-pressed="true"] { background: var(--vscode-list-activeSelectionBackground, var(--vscode-button-secondaryBackground)); color: var(--vscode-list-activeSelectionForeground, var(--vscode-foreground)); }',
    '    .candidate-chords { font-weight: 600; overflow-wrap: anywhere; }',
    '    .candidate-rationale { color: var(--vscode-descriptionForeground); font-size: .92em; overflow-wrap: anywhere; }',
    '    .candidate-list button[aria-pressed="true"] .candidate-rationale { color: inherit; }',
    '    .toolbar { align-items: center; margin-top: 14px; }',
    '    .side-group { display: flex; gap: 4px; }',
    '    .mode-control { display: inline-flex; align-items: center; gap: 6px; }',
    '    .mode-control select { flex: 1; min-width: 132px; }',
    '    .speed-control { display: inline-flex; align-items: center; gap: 6px; margin-left: auto; }',
    '    .speed-control select { min-width: 78px; }',
    '    .actions { display: flex; gap: 6px; margin-top: 14px; }',
    '    #progression-apply { background: var(--vscode-button-background); color: var(--vscode-button-foreground); }',
    '    #progression-apply:hover:not(:disabled) { background: var(--vscode-button-hoverBackground); }',
    '    .error { margin: 10px 0 0; color: var(--vscode-errorForeground); }',
    '    @media (max-width: 600px) { main { padding: 12px; } .mode-control { flex: 1 1 100%; flex-direction: column; align-items: stretch; } .mode-control select { min-width: 0; width: 100%; box-sizing: border-box; } .speed-control { margin-left: 0; } .toolbar { align-items: stretch; } }',
    '  </style>',
    '</head>',
    '<body>',
    '  <main id="inspector-state" data-generation="' + safeGeneration + '" data-context-kind="' + context.kind + '" aria-label="' + escapeHtml(messages.inspectorRegionLabel) + '" aria-labelledby="inspector-heading">',
    '    <h1 id="inspector-heading">' + escapeHtml(messages.inspectorHeading) + '</h1>',
    '    <div id="document-state">',
    '      <p id="inspector-status" class="status" role="status" aria-live="polite">' + escapeHtml(status) + '</p>',
    '      <p id="inspector-description" class="description">' + escapeHtml(description) + '</p>',
    '    </div>',
    '    <section id="progression-state" aria-labelledby="progression-heading" hidden>',
    '      <h2 id="progression-heading"></h2>',
    '      <p id="progression-description" class="description"></p>',
    '      <fieldset><legend id="bars-legend"></legend><div class="choice-row" id="bars-options"></div></fieldset>',
    '      <fieldset><legend id="operation-legend"></legend><div class="choice-row" id="operation-options"></div></fieldset>',
    '      <h2 id="candidate-heading"></h2>',
    '      <p id="progression-repeat-notice" class="description repeat-notice"' + repeatNoticeVisibility + '></p>',
    '      <ul id="candidate-list" class="candidate-list"></ul>',
    '      <p id="progression-error" class="error" role="alert" hidden></p>',
    '      <div class="toolbar">',
    '        <button id="progression-play" type="button"></button>',
    '        <button id="progression-stop" type="button"></button>',
    '        <label class="mode-control"><span id="audition-mode-label"></span><select id="progression-audition-mode">',
    '          <option value="chord">' + escapeHtml(messages.uiProgressionChord) + '</option>',
    '          <option value="bars">' + escapeHtml(messages.uiProgressionBars) + '</option>',
    '          <option value="melody">' + escapeHtml(messages.uiProgressionWithMelody) + '</option>',
    '          <option value="song">' + escapeHtml(messages.uiProgressionFullSong) + '</option>',
    '        </select></label>',
    '        <div class="side-group" role="group" aria-label="' + escapeHtml(messages.uiProgressionTitle) + '">',
    '          <button id="progression-side-a" type="button" aria-pressed="false"></button>',
    '          <button id="progression-side-b" type="button" aria-pressed="false"></button>',
    '        </div>',
    '        <label class="speed-control"><span id="speed-label"></span><select id="progression-speed">',
    '          <option value="50">50%</option><option value="75">75%</option><option value="100">100%</option><option value="125">125%</option><option value="150">150%</option>',
    '        </select></label>',
    '      </div>',
    '      <div class="actions">',
    '        <button id="progression-apply" type="button"></button>',
    '        <button id="progression-cancel" type="button"></button>',
    '      </div>',
    '    </section>',
    '  </main>',
    '  <script nonce="' + safeNonce + '">',
    '    (() => {',
    '      const root = document.getElementById("inspector-state");',
    '      const documentState = document.getElementById("document-state");',
    '      const progressionState = document.getElementById("progression-state");',
    '      const status = document.getElementById("inspector-status");',
    '      const description = document.getElementById("inspector-description");',
    '      const progressionDescription = document.getElementById("progression-description");',
    '      const progressionError = document.getElementById("progression-error");',
    '      const repeatNotice = document.getElementById("progression-repeat-notice");',
    '      const candidateList = document.getElementById("candidate-list");',
    '      const auditionMode = document.getElementById("progression-audition-mode");',
    '      const speed = document.getElementById("progression-speed");',
    '      const labels = ' + safeLabels + ';',
    '      const initial = ' + safeInitial + ';',
    '      let lastGeneration = Number(root.dataset.generation);',
    '      let currentContext = initial.context;',
    '      const vscodeApi = acquireVsCodeApi();',
    '      document.getElementById("bars-legend").textContent = labels.bars;',
    '      document.getElementById("operation-legend").textContent = labels.operation;',
    '      document.getElementById("candidate-heading").textContent = labels.candidates;',
    '      document.getElementById("progression-play").textContent = labels.play;',
    '      document.getElementById("audition-mode-label").textContent = labels.auditionMode;',
    '      repeatNotice.textContent = labels.repeatNotice;',
    '      document.getElementById("progression-stop").textContent = labels.stop;',
    '      document.getElementById("progression-side-a").textContent = labels.sideA;',
    '      document.getElementById("progression-side-b").textContent = labels.sideB;',
    '      document.getElementById("speed-label").textContent = labels.speed;',
    '      document.getElementById("progression-apply").textContent = labels.apply;',
    '      document.getElementById("progression-cancel").textContent = labels.cancel;',
      '      document.getElementById("progression-heading").textContent = labels.progressionTitle;',
    '      const makeChoice = (containerId, values, labelsByValue, allowedValues, command, valueKey, activeValue) => {',
    '        const container = document.getElementById(containerId);',
    '        const control = valueKey === "bars" ? "bars" : "operation";',
    '        const existing = new Map(Array.from(container.children).map(button => [button.dataset.inspectorKey, button]));',
    '        values.forEach((value, index) => {',
    '          const key = String(value);',
    '          let button = existing.get(key);',
    '          if (!button) {',
    '            button = document.createElement("button");',
    '            button.type = "button";',
    '            button.dataset.inspectorControl = control;',
    '            button.dataset.inspectorKey = key;',
    '            button.addEventListener("click", () => post(command, { [valueKey]: value }));',
    '          }',
    '          existing.delete(key);',
    '          button.textContent = labelsByValue[value];',
    '          button.disabled = !allowedValues.includes(value);',
    '          button.setAttribute("aria-pressed", String(value === activeValue));',
    '          if (container.children[index] !== button) container.insertBefore(button, container.children[index] || null);',
    '        });',
    '        for (const obsolete of existing.values()) obsolete.remove();',
    '      };',
    '      const post = (command, extra = {}) => {',
    '        const context = currentContext;',
    '        if (!context || context.kind !== "progression") return;',
    '        vscodeApi.postMessage({ command, generation: lastGeneration, sessionUri: context.uri, sessionVersion: context.version, sessionGeneration: context.sessionGeneration, selectedCandidateId: context.selectedCandidateId, ...extra });',
    '      };',
    '      const restoreControlFocus = (focusedControl, focusedKey) => {',
    '        if (!focusedControl) return;',
    '        const containerId = focusedControl === "candidate" ? "candidate-list" : focusedControl === "bars" ? "bars-options" : "operation-options";',
    '        const container = document.getElementById(containerId);',
    '        const buttons = Array.from(container.querySelectorAll("button"));',
    '        const focused = buttons.find(button => button.dataset.inspectorKey === focusedKey && !button.disabled);',
    '        const fallback = focusedControl === "candidate"',
    '          ? buttons.find(button => button.getAttribute("aria-pressed") === "true" && !button.disabled) || buttons.find(button => !button.disabled)',
    '          : buttons.find(button => button.getAttribute("aria-pressed") === "true" && !button.disabled) || buttons.find(button => !button.disabled);',
    '        const target = focused || fallback;',
    '        if (target) { if (document.activeElement !== target) target.focus(); return; }',
    '        const fallbackHeading = document.getElementById(focusedControl === "candidate" ? "candidate-heading" : "progression-heading");',
    '        fallbackHeading.tabIndex = -1;',
    '        fallbackHeading.focus();',
    '      };',
    '      const render = (context, nextStatus, nextDescription) => {',
    '        const focusedElement = document.activeElement;',
    '        const focusedControl = focusedElement && focusedElement.dataset ? focusedElement.dataset.inspectorControl : null;',
    '        const focusedKey = focusedElement && focusedElement.dataset ? focusedElement.dataset.inspectorKey : null;',
    '        currentContext = context;',
    '        root.dataset.contextKind = context.kind;',
    '        document.getElementById("inspector-heading").textContent = labels.heading;',
    '        documentState.hidden = context.kind === "progression";',
    '        progressionState.hidden = context.kind !== "progression";',
    '        if (context.kind !== "progression") { status.textContent = nextStatus; description.textContent = nextDescription; return; }',
    '        progressionDescription.textContent = context.loading ? labels.loading : nextDescription;',
    '        repeatNotice.hidden = context.target.bars <= 4;',
    '        progressionError.textContent = context.error || "";',
    '        progressionError.hidden = !context.error;',
    '        makeChoice("bars-options", [4, 8, 16], { 4: labels.lengthFour, 8: labels.lengthEight, 16: labels.lengthSixteen }, context.availableBars || [], "progressionSetBars", "bars", context.target.bars);',
    '        makeChoice("operation-options", ["replace", "append"], { replace: labels.replace, append: labels.append }, context.availableOperations || [], "progressionSetOperation", "operation", context.target.operation);',
    '        const existingCandidates = new Map(Array.from(candidateList.children).map(item => [item.dataset.candidateId, item]));',
    '        const candidates = (context.candidates || []).slice(0, 5);',
    '        candidates.forEach((candidate, index) => {',
    '          let item = existingCandidates.get(candidate.id);',
    '          let button;',
    '          let chords;',
    '          let rationale;',
    '          if (item) { button = item.querySelector("button"); chords = button.children[0]; rationale = button.children[1]; }',
    '          else {',
    '            item = document.createElement("li");',
    '            item.dataset.candidateId = candidate.id;',
    '            button = document.createElement("button");',
    '            button.type = "button";',
    '            button.dataset.inspectorControl = "candidate";',
    '            button.dataset.inspectorKey = candidate.id;',
    '            chords = document.createElement("span"); chords.className = "candidate-chords";',
    '            rationale = document.createElement("span"); rationale.className = "candidate-rationale";',
    '            button.append(chords, rationale);',
    '            button.addEventListener("click", () => post("progressionCandidateChanged", { candidateId: candidate.id, selectedCandidateId: candidate.id }));',
    '            item.append(button);',
    '          }',
    '          existingCandidates.delete(candidate.id);',
    '          button.setAttribute("aria-pressed", String(candidate.id === context.selectedCandidateId));',
    '          chords.textContent = candidate.chords.join("  →  ");',
    '          rationale.textContent = [candidate.scoreText || String(candidate.score), candidate.rationale].filter(Boolean).join(" · ");',
    '          if (candidateList.children[index] !== item) candidateList.insertBefore(item, candidateList.children[index] || null);',
    '        });',
    '        for (const obsolete of existingCandidates.values()) obsolete.remove();',
    '        const hasCandidate = (context.candidates || []).some(candidate => candidate.id === context.selectedCandidateId);',
    '        document.getElementById("progression-play").disabled = !hasCandidate || context.loading;',
    '        document.getElementById("progression-stop").disabled = context.loading;',
    '        document.getElementById("progression-side-a").setAttribute("aria-pressed", String(context.side === "A"));',
    '        document.getElementById("progression-side-b").setAttribute("aria-pressed", String(context.side === "B"));',
    '        auditionMode.value = context.auditionMode;',
    '        auditionMode.disabled = context.loading;',
    '        speed.value = String(context.auditionSpeed);',
    '        speed.disabled = context.loading;',
    '        document.getElementById("progression-apply").disabled = !hasCandidate || context.loading;',
    '        restoreControlFocus(focusedControl, focusedKey);',
    '      };',
    '      document.getElementById("progression-play").addEventListener("click", () => post("progressionPlay"));',
    '      document.getElementById("progression-stop").addEventListener("click", () => post("progressionStop"));',
    '      auditionMode.addEventListener("change", () => post("progressionAuditionModeChanged", { mode: auditionMode.value }));',
    '      document.getElementById("progression-side-a").addEventListener("click", () => post("progressionSideChanged", { side: "A" }));',
    '      document.getElementById("progression-side-b").addEventListener("click", () => post("progressionSideChanged", { side: "B" }));',
    '      speed.addEventListener("change", () => post("progressionSpeedChanged", { speed: Number(speed.value) }));',
    '      document.getElementById("progression-apply").addEventListener("click", () => post("progressionApply"));',
    '      document.getElementById("progression-cancel").addEventListener("click", () => post("progressionDismiss"));',
    '      window.addEventListener("message", event => {',
    '        const message = event.data;',
    '        if (!message || message.command !== "setContext" || !Number.isSafeInteger(message.generation) || message.generation <= lastGeneration) return;',
    '        if (!message.context || !["empty", "document", "progression"].includes(message.context.kind)) return;',
    '        lastGeneration = message.generation;',
    '        root.dataset.generation = String(message.generation);',
    '        render(message.context, message.status, message.description);',
    '      });',
    '      render(initial.context, initial.status, initial.description);',
    '      vscodeApi.postMessage({ command: "ready" });',
    '    })();',
    '  </script>',
    '</body>',
    '</html>'
  ].join('\n');
}

function escapeJsonForHtml(value: string): string {
  return value.replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
